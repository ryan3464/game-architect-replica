// =============== GARDEN / CAMPAGNA ===============
/** A planted plot in the player's garden. Generated by completing a level. */
export interface GardenPlant {
  id: string;
  /** Source level id (1..N) — drives the fruit shown and yield rate */
  levelId: number;
  plantedAt: number;
}

/** Coins-per-minute by source level. */
export const GARDEN_RATE_BY_LEVEL: Record<number, number> = {
  1: 1, 2: 2, 3: 3, 4: 5,
};
export const GARDEN_MAX_ACCUMULATION_MS = 8 * 60 * 60 * 1000; // 8h
export const GARDEN_MAX_PLOTS = 12;

export function computePlantPending(plant: GardenPlant, lastClaim: number, nowMs: number): number {
  const rate = GARDEN_RATE_BY_LEVEL[plant.levelId] ?? 1;
  const start = Math.max(plant.plantedAt, lastClaim);
  const elapsed = Math.min(GARDEN_MAX_ACCUMULATION_MS, Math.max(0, nowMs - start));
  return Math.floor((elapsed / 60_000) * rate);
}

